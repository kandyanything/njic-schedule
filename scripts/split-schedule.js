// Split data/schedule.json into per-month files the site can load one at a time.
//
// The combined file is several megabytes - far too much to send to every
// visitor. The calendar loads a small index to draw the month grid, then pulls
// only the month being viewed.
//
// Run: node scripts/split-schedule.js
// Output: data/schedule/index.json and data/schedule/YYYY-MM.json

const fs = require('fs');
const path = require('path');
const { logoSlug } = require('./school-logos');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'data', 'schedule.json');
const OUT = path.join(ROOT, 'data', 'schedule');

const doc = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const games = doc.games || [];
if (!games.length) throw new Error('schedule.json has no games - refusing to publish an empty calendar');

fs.mkdirSync(OUT, { recursive: true });

// clear out months that no longer have games, so a stale file cannot linger
for (const f of fs.readdirSync(OUT)) {
    if (/^\d{4}-\d{2}\.json$/.test(f)) fs.unlinkSync(path.join(OUT, f));
}

const byMonth = new Map();
const byDate = new Map();
for (const g of games) {
    const month = g.date.slice(0, 7);
    if (!byMonth.has(month)) byMonth.set(month, []);
    byMonth.get(month).push(g);
    byDate.set(g.date, (byDate.get(g.date) || 0) + 1);
}

// The month files are downloaded by visitors, so they carry only what the
// calendar renders. The internal de-duplication id, the source name and the
// list of contributing schools are all build-time concerns and stay in
// schedule.json, which is never served.
function slim(g) {
    const out = {
        date: g.date,
        time: g.time,
        timeLabel: g.timeLabel,
        sport: g.sport,
        school: g.school,
    };
    if (g.level) out.level = g.level;
    if (g.gender) out.gender = g.gender;
    if (g.opponent) out.opponent = g.opponent;
    if (g.home !== null && g.home !== undefined) out.home = g.home;
    if (g.status) out.status = g.status;
    if (g.kind && g.kind !== 'Game') out.kind = g.kind;
    // The reporting school is always a conference school, so it always has a
    // crest. The opponent gets one only when it is also a conference school -
    // an out-of-conference opponent stays crest-less.
    const sLogo = logoSlug(g.school);
    if (sLogo) out.schoolLogo = sLogo;
    if (g.opponent) {
        const oLogo = logoSlug(g.opponent);
        if (oLogo) out.oppLogo = oLogo;
    }
    return out;
}

let total = 0;
const months = [];
for (const [month, list] of [...byMonth.entries()].sort()) {
    list.sort((a, b) => (a.date === b.date
        ? (a.time || '99:99').localeCompare(b.time || '99:99')
        : a.date.localeCompare(b.date)));
    const file = path.join(OUT, `${month}.json`);
    fs.writeFileSync(file, JSON.stringify({ month, games: list.map(slim) }) + '\n');
    const kb = fs.statSync(file).size / 1024;
    total += kb;
    months.push({ month, games: list.length, kb: Math.round(kb) });
}

// The index carries only what the month grid needs: which dates have games and
// how many. Small enough to load on every visit.
const counts = {};
for (const [date, n] of [...byDate.entries()].sort()) counts[date] = n;

const sports = [...new Set(games.map(g => g.sport))].sort();
const index = {
    _comment: 'Generated by scripts/split-schedule.js. Load this for the month grid, then data/schedule/YYYY-MM.json for a month of games.',
    generated: doc.generated,
    range: doc.range,
    counts: doc.counts,
    coverage: doc.coverage,
    months: months.map(m => m.month),
    sports,
    dateCounts: counts,
};
fs.writeFileSync(path.join(OUT, 'index.json'), JSON.stringify(index, null, 2) + '\n');
const indexKb = fs.statSync(path.join(OUT, 'index.json')).size / 1024;

// The homepage shows the next few days. Pulling a whole month for that would
// cost up to 557 KB, so the window is written out separately.
//
// It is measured from the build, not from the reader's clock, so it carries
// slack: eight days means a missed nightly run or two still leaves something to
// show, and the page filters to the reader's own date anyway.
const WINDOW_DAYS = 8;
const easternDate = d => new Intl.DateTimeFormat('en-CA', {
    timeZone: 'America/New_York', year: 'numeric', month: '2-digit', day: '2-digit',
}).format(d);

const from = easternDate(new Date(doc.generated || Date.now()));
const end = new Date(from + 'T12:00:00Z');
end.setUTCDate(end.getUTCDate() + WINDOW_DAYS - 1);
const through = end.toISOString().slice(0, 10);

const upcoming = games
    .filter(g => g.date >= from && g.date <= through)
    .sort((a, b) => (a.date === b.date
        ? (a.time || '99:99').localeCompare(b.time || '99:99')
        : a.date.localeCompare(b.date)));

fs.writeFileSync(path.join(OUT, 'upcoming.json'),
    JSON.stringify({ generated: doc.generated, from, through, games: upcoming.map(slim) }) + '\n');
const upKb = fs.statSync(path.join(OUT, 'upcoming.json')).size / 1024;

console.log(`  ${games.length} games across ${months.length} months, ${Object.keys(counts).length} dates`);
months.forEach(m => console.log(`    ${m.month}  ${String(m.games).padStart(4)} games  ${String(m.kb).padStart(4)} KB`));
console.log(`  index.json ${indexKb.toFixed(0)} KB   months total ${Math.round(total)} KB`);
console.log(`  upcoming.json ${upKb.toFixed(0)} KB  ${upcoming.length} games, ${from} .. ${through}`);
console.log(`  largest month: ${Math.max(...months.map(m => m.kb))} KB  (was ${Math.round(fs.statSync(SRC).size / 1024)} KB as one file)`);
